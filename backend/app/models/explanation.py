
from enum import Enum

from pydantic import BaseModel, ConfigDict, Field, model_validator


class SectionStatus(str, Enum):
    AVAILABLE = "available"
    NOT_SPECIFIED = "not_specified"


class EvidenceBasis(str, Enum):
    DIRECT = "directly_stated"
    INTERPRETATION = "cautious_interpretation"


class EvidenceReference(BaseModel):
    """Actual source information attached by our backend."""

    model_config = ConfigDict(extra="forbid")

    source_number: int = Field(ge=1)
    document_id: str
    filename: str
    page_number: int = Field(ge=1)

    language_label: str | None = None
    language_code: str | None = None
    script: str | None = None
    detection_model: str | None = None
    detection_raw_score: float | None = None


class CitedPoint(BaseModel):
    """One factual statement supported by retrieved evidence."""

    model_config = ConfigDict(extra="forbid")

    text: str = Field(min_length=1)
    source_numbers: list[int] = Field(min_length=1)

    evidence_basis: EvidenceBasis = EvidenceBasis.DIRECT


class PolicySection(BaseModel):
    """A policy explanation section."""

    model_config = ConfigDict(extra="forbid")

    status: SectionStatus
    points: list[CitedPoint] = Field(default_factory=list)

    @model_validator(mode="after")
    def validate_section_content(self):
        if self.status == SectionStatus.AVAILABLE and not self.points:
            raise ValueError(
                "An available section must contain at least one point."
            )

        if (
            self.status == SectionStatus.NOT_SPECIFIED
            and self.points
        ):
            raise ValueError(
                "A not_specified section cannot contain points."
            )

        return self


class PolicyExplanationDraft(BaseModel):
    """
    Structured content generated by Gemini.
    Does not contain document metadata.
    """

    model_config = ConfigDict(extra="forbid")

    policy_overview: PolicySection
    eligibility: PolicySection
    rights_and_benefits: PolicySection
    obligations: PolicySection
    application_process: PolicySection
    deadlines_and_conditions: PolicySection
    real_world_impact: PolicySection

    information_not_found: list[str] = Field(
        default_factory=list
    )


class PolicyExplanation(PolicyExplanationDraft):
    """Final explanation validated and enriched by our backend."""

    question: str
    answer_language: str

    sources: list[EvidenceReference] = Field(
        default_factory=list
    )

    @model_validator(mode="after")
    def validate_source_references(self):
        source_numbers = [
            source.source_number
            for source in self.sources
        ]

        if len(source_numbers) != len(set(source_numbers)):
            raise ValueError("Source numbers must be unique.")

        valid_numbers = set(source_numbers)

        sections = [
            self.policy_overview,
            self.eligibility,
            self.rights_and_benefits,
            self.obligations,
            self.application_process,
            self.deadlines_and_conditions,
            self.real_world_impact,
        ]

        for section in sections:
            for point in section.points:
                invalid_numbers = (
                    set(point.source_numbers) - valid_numbers
                )

                if invalid_numbers:
                    raise ValueError(
                        f"Unknown source numbers: {invalid_numbers}"
                    )

        return self
